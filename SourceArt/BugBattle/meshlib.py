def lathe_x(mesh, mat, profile, segs=48, offset=(0, 0, 0), yscale=1.0, zscale=1.0, v0=0.0, v1=1.0):
    """profile: list of (x, r) along +X. Surface of revolution around X axis."""
    n = len(profile) - 1

    def fn(u, v):
        k = v * n
        i = min(int(k), n - 1)
        t = k - i
        x = profile[i][0] * (1 - t) + profile[i + 1][0] * t
        r = profile[i][1] * (1 - t) + profile[i + 1][1] * t
        a = u * 2 * math.pi
        return (offset[0] + x, offset[1] + r * math.sin(a) * yscale, offset[2] + r * math.cos(a) * zscale)
    return mesh.grid(mat, segs, n, fn, uv_fn=lambda u, v: (u, v0 + (v1 - v0) * v), wrap_u=True, flip=True)


def ellipsoid(mesh, mat, center, radii, nu=40, nv=24, deform=None):
    def fn(u, v):
        th = v * math.pi
        ph = u * 2 * math.pi
        d = (math.sin(th) * math.cos(ph), math.sin(th) * math.sin(ph), math.cos(th))
        p = (d[0] * radii[0], d[1] * radii[1], d[2] * radii[2])
        if deform:
            p = deform(p, d)
        return v_add(center, p)
    return mesh.grid(mat, nu, nv, fn, wrap_u=True, flip=True)


def tube_along(mesh, mat, pts, radii, segs=12, cap=True):
    """Tube through polyline pts with per-point radii (parallel-transport frames)."""
    n = len(pts)
    tangents = []
    for i in range(n):
        a = pts[max(i - 1, 0)]
        b = pts[min(i + 1, n - 1)]
        tangents.append(v_norm(v_sub(b, a)))
    up = (0, 0, 1) if abs(tangents[0][2]) < 0.9 else (1, 0, 0)
    nrm = v_norm(v_cross(tangents[0], up))
    rings = []
    for i in range(n):
        t = tangents[i]
        nrm = v_norm(v_sub(nrm, v_mul(t, v_dot(nrm, t))))
        bin_ = v_cross(t, nrm)
        ring = []
        for s in range(segs):
            a = 2 * math.pi * s / segs
            d = v_add(v_mul(nrm, math.cos(a)), v_mul(bin_, math.sin(a)))
            ring.append(mesh.vert(v_add(pts[i], v_mul(d, radii[i])), (s / segs, i / (n - 1)), d))
        rings.append(ring)
    for i in range(n - 1):
        for s in range(segs):
            s2 = (s + 1) % segs
            mesh.quad(mat, rings[i][s], rings[i + 1][s], rings[i + 1][s2], rings[i][s2])
    if cap:
        for end, ring, sign in ((0, rings[0], -1), (n - 1, rings[-1], 1)):
            c = mesh.vert(v_add(pts[end], v_mul(tangents[end], radii[end] * 0.6 * sign)), (0.5, 0.5),
                          v_mul(tangents[end], sign))
            for s in range(segs):
                s2 = (s + 1) % segs
                mesh.tri(mat, c, ring[s2], ring[s]) if sign > 0 else mesh.tri(mat, c, ring[s], ring[s2])


def catmull(pts, samples=6):
    out = []
    P = [pts[0]] + list(pts) + [pts[-1]]
    for i in range(1, len(P) - 2):
        p0, p1, p2, p3 = P[i - 1], P[i], P[i + 1], P[i + 2]
        for k in range(samples):
            t = k / samples
            t2, t3 = t * t, t * t * t
            out.append(tuple(0.5 * ((2 * p1[j]) + (-p0[j] + p2[j]) * t + (2 * p0[j] - 5 * p1[j] + 4 * p2[j] - p3[j]) * t2
                                    + (-p0[j] + 3 * p1[j] - 3 * p2[j] + p3[j]) * t3) for j in range(3)))
    out.append(tuple(pts[-1]))
    return out


class Rng:
    """Deterministic LCG so meshes are reproducible."""
    def __init__(self, seed):
        self.s = seed & 0xFFFFFFFF

    def f(self):
        self.s = (1664525 * self.s + 1013904223) & 0xFFFFFFFF
        return self.s / 4294967296.0

    def r(self, a, b):
        return a + (b - a) * self.f()
