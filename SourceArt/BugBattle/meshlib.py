"""Tiny procedural mesh toolkit that writes OBJ files for Unreal import.

All geometry is authored in Unreal space (X forward, Y right, Z up, cm).
The Unreal OBJ importer maps OBJ (x, y, z) -> UE (x, -y, z), so the writer
negates Y and fixes triangle winding to match the authored normals.
"""
import math


def v_add(a, b): return (a[0] + b[0], a[1] + b[1], a[2] + b[2])
def v_sub(a, b): return (a[0] - b[0], a[1] - b[1], a[2] - b[2])
def v_mul(a, s): return (a[0] * s, a[1] * s, a[2] * s)
def v_dot(a, b): return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
def v_cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])
def v_len(a): return math.sqrt(v_dot(a, a))
def v_norm(a):
    l = v_len(a)
    return (0.0, 0.0, 1.0) if l < 1e-12 else (a[0] / l, a[1] / l, a[2] / l)


class Mesh:
    def __init__(self):
        self.p = []      # positions
        self.n = []      # normals (None -> computed smooth)
        self.uv = []
        self.tris = {}   # material -> list of (i, j, k)

    def vert(self, pos, uv=(0.0, 0.0), normal=None):
        self.p.append(tuple(pos))
        self.uv.append(tuple(uv))
        self.n.append(normal)
        return len(self.p) - 1

    def tri(self, mat, a, b, c):
        self.tris.setdefault(mat, []).append((a, b, c))

    def quad(self, mat, a, b, c, d):
        self.tri(mat, a, b, c)
        self.tri(mat, a, c, d)

    def grid(self, mat, nu, nv, fn, uv_fn=None, wrap_u=False, flip=False):
        """Parametric surface. fn(u, v) -> pos for u, v in [0, 1].
        Normals are smooth-averaged afterwards. Front face follows
        cross(dP/du, dP/dv) unless flip is set."""
        cols = nu if wrap_u else nu + 1
        idx = []
        for j in range(nv + 1):
            row = []
            v = j / nv
            for i in range(cols):
                u = i / nu
                uv = uv_fn(u, v) if uv_fn else (u, v)
                row.append(self.vert(fn(u, v), uv))
            idx.append(row)
        group = []
        for j in range(nv):
            for i in range(nu):
                i2 = (i + 1) % cols if wrap_u else i + 1
                a, b, c, d = idx[j][i], idx[j][i2], idx[j + 1][i2], idx[j + 1][i]
                if flip:
                    self.quad(mat, a, d, c, b)
                else:
                    self.quad(mat, a, b, c, d)
        return idx

    def append(self, other, xform=None):
        base = len(self.p)
        for i, pos in enumerate(other.p):
            n = other.n[i]
            if xform:
                pos, n = xform(pos, n)
            self.p.append(pos)
            self.n.append(n)
            self.uv.append(other.uv[i])
        for m, ts in other.tris.items():
            for (a, b, c) in ts:
                self.tri(m, a + base, b + base, c + base)

    def compute_normals(self):
        acc = [(0.0, 0.0, 0.0)] * len(self.p)
        for ts in self.tris.values():
            for (a, b, c) in ts:
                fn = v_cross(v_sub(self.p[b], self.p[a]), v_sub(self.p[c], self.p[a]))
                for k in (a, b, c):
                    acc[k] = v_add(acc[k], fn)
        for i in range(len(self.p)):
            if self.n[i] is None:
                self.n[i] = v_norm(acc[i])
            else:
                self.n[i] = v_norm(self.n[i])

    def weld_seams(self, eps=0.01):
        """Average normals of coincident vertices (for wrap seams/poles)."""
        buckets = {}
        for i, pos in enumerate(self.p):
            key = (round(pos[0] / eps), round(pos[1] / eps), round(pos[2] / eps))
            buckets.setdefault(key, []).append(i)
        for ids in buckets.values():
            if len(ids) > 1:
                s = (0.0, 0.0, 0.0)
                for i in ids:
                    s = v_add(s, self.n[i])
                s = v_norm(s)
                for i in ids:
                    self.n[i] = s

    def write_obj(self, path, smooth_weld=True):
        if any(n is None for n in self.n):
            self.compute_normals()
        if smooth_weld:
            self.weld_seams()
        lines = ["# generated by meshlib.py"]
        for (x, y, z) in self.p:
            lines.append("v %.4f %.4f %.4f" % (x, -y, z))
        for (u, v) in self.uv:
            lines.append("vt %.5f %.5f" % (u, 1.0 - v))
        for (x, y, z) in self.n:
            lines.append("vn %.5f %.5f %.5f" % (x, -y, z))
        for mat, ts in self.tris.items():
            lines.append("usemtl %s" % mat)
            lines.append("g %s" % mat)
            for (a, b, c) in ts:
                # Winding in OBJ space must give the authored normal after the
                # Y mirror; mirrored space reverses orientation, so swap b/c.
                pa, pb, pc = self.p[a], self.p[b], self.p[c]
                gn = v_cross(v_sub(pb, pa), v_sub(pc, pa))
                want = v_add(v_add(self.n[a], self.n[b]), self.n[c])
                if v_dot(gn, want) < 0:
                    b, c = c, b
                # mirrored: reverse
                a1, b1, c1 = a + 1, c + 1, b + 1
                lines.append("f %d/%d/%d %d/%d/%d %d/%d/%d" % (a1, a1, a1, b1, b1, b1, c1, c1, c1))
        with open(path, "w") as f:
            f.write("\n".join(lines) + "\n")
        ntri = sum(len(t) for t in self.tris.values())
        return ntri


