"""Test-only autopilot for handling tests on Lvl_GardenGrandPrix (not used by any car).

Writes:
  autopilot.dsl            BPC_RGC_AutoPilot event graph (pure-pursuit steering along the centreline,
                           throttle/brake against a corner speed cap, telemetry to the log every 0.25 s)
  autopilot_defaults.json  Pts / Yaw / Rad for the component (centreline every 4 m, min radius ahead)
Copies go to Saved/RacingGame/*.txt|json (AssetTools.read_file only reads there).

A car stuck for 1.5 s is reset onto the centreline (AP_RESET|idx in the log).
Telemetry line:  AP|t|idx|kmh|cap|slip|roll|lat|steer|thr|brk
  slip = angle between velocity and the car's nose (deg), lat = metres right of the centreline.
Parse with parse_autopilot.py.
"""
import json, math, os
import numpy as np
from trackdef import Track

HERE = os.path.dirname(os.path.abspath(__file__))
SAVED = os.path.join(HERE, "..", "..", "Saved", "RacingGame")
STRIDE = 4            # centreline samples are 100 cm apart -> a waypoint every 4 m
AHEAD_M = 60          # corner speed cap looks this far ahead for the tightest radius

T = Track()
n = len(T.xy)
pts, yaws, rads = [], [], []
R = 1.0 / np.maximum(np.abs(T.curv), 1e-6)
for i in range(0, n, STRIDE):
    c, fwd, _, _ = T.frame(i)
    pts.append({"x": round(float(c[0]), 1), "y": round(float(c[1]), 1), "z": round(float(c[2]), 1)})
    yaws.append(round(math.degrees(math.atan2(fwd[1], fwd[0])), 2))
    ahead = [R[(i + k) % n] for k in range(0, AHEAD_M * 100 // int(T.step) + 1)]
    rads.append(round(float(min(min(ahead), 100000.0)), 0))
defaults = {"Pts": pts, "Yaw": yaws, "Rad": rads}

DSL = r"""; BPC_RGC_AutoPilot event graph (generated by gen_autopilot.py). Test-only: add to an unpossessed racer.
(event EventTick (DeltaSeconds)
  (bind owner (Components|GetOwner))
  (bind mc (Class|WheeledVehiclePawn|GetVehicleMovementComponent (Utilities|Casting|CastToWheeledVehiclePawn owner)))
  (bind pts (Variables|Default|GetPts))
  (bind n (Utilities|Array|Length pts))
  (bind loc (Transformation|GetActorLocation :self owner))
  (bind i0 (Variables|Default|GetIdx))
  (Variables|Default|SetBestD 1000000000000.0)
  (for k (range 0 14)
    (bind j (Math|Integer|%(Integer) (+ (+ i0 k) (- n 3)) n))
    (bind d (Math|Vector|Distance2DSquared(Vector) loc (Utilities|Array|Get(acopy) pts j)))
    (if (< d (Variables|Default|GetBestD))
      (Variables|Default|SetBestD d)
      (Variables|Default|SetBestI j)))
  (bind idx (Variables|Default|GetBestI))
  (Variables|Default|SetIdx idx)
  (bind vel (Transformation|GetVelocity owner))
  (bind spd (Math|Vector|VectorLength vel))
  (bind kmh (* spd 0.036))
  ; pure pursuit: look-ahead 6 m + 0.45 s of travel
  (bind ld (+ 600.0 (* spd 0.45)))
  (bind steps (Math|Float|Truncate (/ ld 400.0)))
  (bind tgt (Utilities|Array|Get(acopy) pts (Math|Integer|%(Integer) (+ idx (+ steps 1)) n)))
  (bind lp (Math|Transform|InverseTransformLocation (Transformation|GetActorTransform owner) tgt))
  (bind alpha (Math|Trig|Atan2(Degrees) (.y lp) (.x lp)))
  (bind ldist (Math|Float|Max(Float) (Math|Vector|VectorLength lp) 300.0))
  (bind delta (Math|Trig|Atan(Degrees) (/ (* 528.0 (Math|Trig|Sin(Degrees) alpha)) ldist)))
  (bind lock (* 32.0 (Math|Float|Max(Float) 0.42 (- 1.0 (* kmh 0.0046)))))
  (bind steer (Math|Float|Clamp(Float) (/ delta lock) -1.0 1.0))
  ; corner speed cap from the tightest radius ahead
  (bind rad (Utilities|Array|Get(acopy) (Variables|Default|GetRad) idx))
  (bind cap (* 0.036 (Math|Float|Sqrt (* (* (Variables|Default|GetLatG) 981.0) rad))))
  (bind thr (select (> kmh cap) 0.0 1.0))
  (bind brk (select (> kmh (+ cap 6.0)) 1.0 0.0))
  (Game|Components|ChaosVehicleMovement|SetSteeringInput mc steer)
  (Game|Components|ChaosVehicleMovement|SetThrottleInput mc thr)
  (Game|Components|ChaosVehicleMovement|SetBrakeInput mc brk)
  ; stuck for 1.5 s (spun into a wall) -> put back on the centreline like the race manager does; logged as AP_RESET
  (bind now (Utilities|Time|GetGameTimeinSeconds))
  (if (and (< kmh 5.0) (> now 3.0))
    (Variables|Default|SetStuckT (+ (Variables|Default|GetStuckT) DeltaSeconds))
    (else
      (Variables|Default|SetStuckT 0.0)))
  (if (> (Variables|Default|GetStuckT) 1.5)
    (Variables|Default|SetStuckT 0.0)
    (bind rp (Utilities|Array|Get(acopy) pts idx))
    (bind body (Actor|GetComponentbyClass :self owner :ComponentClass "/Script/Engine.SkeletalMeshComponent"))
    (Physics|SetPhysicsLinearVelocity :self body :NewVel (Math|Vector|MakeVector :X 0.0 :Y 0.0 :Z 0.0))
    (Physics|SetPhysicsAngularVelocityinDegrees :self body :NewAngVel (Math|Vector|MakeVector :X 0.0 :Y 0.0 :Z 0.0))
    (Transformation|SetActorLocationAndRotation :self owner
      :NewLocation (+ rp (Math|Vector|MakeVector :X 0.0 :Y 0.0 :Z 80.0))
      :NewRotation (Math|Rotator|MakeRotator :Roll 0.0 :Pitch 0.0 :Yaw (Utilities|Array|Get(acopy) (Variables|Default|GetYaw) idx))
      :bSweep false :bTeleport true)
    (Development|PrintString :InString (Utilities|String|Append "AP_RESET|" (Utilities|String|ToString(Integer) idx)) :bPrintToScreen false :bPrintToLog true))
  ; telemetry
  (if (> now (Variables|Default|GetNextLog))
    (Variables|Default|SetNextLog (+ now 0.25))
    (bind fv (Transformation|GetActorForwardVector owner))
    (bind rv (Transformation|GetActorRightVector owner))
    (bind slip (select (> spd 300.0) (Math|Trig|Atan2(Degrees) (Math|Vector|DotProduct vel rv) (Math|Vector|DotProduct vel fv)) 0.0))
    (bind roll (.roll (Transformation|GetActorRotation owner)))
    (bind p (Utilities|Array|Get(acopy) pts idx))
    (bind yw (Utilities|Array|Get(acopy) (Variables|Default|GetYaw) idx))
    (bind lat (/ (+ (* (- (.x loc) (.x p)) (- (Math|Trig|Sin(Degrees) yw))) (* (- (.y loc) (.y p)) (Math|Trig|Cos(Degrees) yw))) 100.0))
    (bind s1 (Utilities|String|Append "AP|" (Utilities|String|ToString(Float) now)))
    (bind s2 (Utilities|String|Append s1 (Utilities|String|Append "|" (Utilities|String|ToString(Integer) idx))))
    (bind s3 (Utilities|String|Append s2 (Utilities|String|Append "|" (Utilities|String|ToString(Float) kmh))))
    (bind s4 (Utilities|String|Append s3 (Utilities|String|Append "|" (Utilities|String|ToString(Float) cap))))
    (bind s5 (Utilities|String|Append s4 (Utilities|String|Append "|" (Utilities|String|ToString(Float) slip))))
    (bind s6 (Utilities|String|Append s5 (Utilities|String|Append "|" (Utilities|String|ToString(Float) roll))))
    (bind s7 (Utilities|String|Append s6 (Utilities|String|Append "|" (Utilities|String|ToString(Float) lat))))
    (bind s8 (Utilities|String|Append s7 (Utilities|String|Append "|" (Utilities|String|ToString(Float) steer))))
    (bind s9 (Utilities|String|Append s8 (Utilities|String|Append "|" (Utilities|String|ToString(Float) thr))))
    (bind s10 (Utilities|String|Append s9 (Utilities|String|Append "|" (Utilities|String|ToString(Float) brk))))
    (Development|PrintString :InString s10 :bPrintToScreen false :bPrintToLog true)))
"""

if __name__ == "__main__":
    os.makedirs(SAVED, exist_ok=True)
    for path in (os.path.join(HERE, "autopilot.dsl"), os.path.join(SAVED, "autopilot.txt")):
        open(path, "w").write(DSL)
    for path in (os.path.join(HERE, "autopilot_defaults.json"), os.path.join(SAVED, "autopilot_defaults.json")):
        json.dump(defaults, open(path, "w"))
    print(len(pts), "waypoints; min radius %.0f cm" % min(rads))
